def _details_stage() -> str:
    """Who answers a deep course-detail request — Nabras itself, or Botpress.

    Constant per process (driven by DETAILS_TO_BOTPRESS), so the prompt stays
    byte-identical between turns and prompt caching is preserved."""
    return (_DETAILS_TO_BOTPRESS if get_settings().details_to_botpress
            else _DETAILS_IN_NABRAS)


def build_system_prompt(catalog_digest: str = "",
                        instructor_digest: str = "") -> str:
    """Both digests are byte-identical between turns, so the whole prompt stays
    prompt-cacheable; they only change when the data behind them changes."""
    out = BASE_PROMPT.replace(_DETAILS_MARKER, _details_stage())
    if catalog_digest:
        out += (
            "\n# كتالوج Engosoft الحالي (مرجع سريع — الأسعار ليست هنا، استخدم get_price)\n"
            "الصيغة: #id | الاسم | التصنيف | نوع التقديم | المدة | الدفعات القادمة\n"
            f"{catalog_digest}\n")
    if instructor_digest:
        out += (
            "\n# مدربو Engosoft (الأسماء الرسمية — طابق اسم العميل عليها بنفسك)\n"
            "الصيغة: #id | الاسم | المسمّى الوظيفي | عدد دوراته\n"
            f"{instructor_digest}\n")
    return out


